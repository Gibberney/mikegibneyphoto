#!/usr/bin/env python3
"""
process-photos.py — turn the originals in /photography into a fast, web-ready
gallery and write galleries/manifest.js for the site to read.

Run it whenever you add, remove, or rename photos:

    python3 tools/process-photos.py

What it does
------------
- Reads every image in  photography/  (your originals are NEVER modified).
- Makes two optimized copies of each in  images/gallery/:
      <slug>.thumb.jpg   small thumbnail for the right-hand grid (long edge 700px)
      <slug>.large.jpg   big version for the viewer + fullscreen (long edge 2560px)
- Pulls your headshot out for the About section (not shown in the grid).
- Skips anything listed in EXCLUDE (e.g. screenshots).
- Writes galleries/manifest.js  ->  window.PHOTOS + window.SITE

Controlling order & captions
----------------------------
- Photos show in alphabetical order. Prefix filenames with numbers to reorder:
  01-colorado.jpg, 02-dunes.jpg ...
- Optional captions: create tools/captions.json like
      { "Fuego Erupt.jpg": "Volcán de Fuego erupting at dawn" }
"""

import os, re, json, sys
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "photography")
OUT_DIR = os.path.join(ROOT, "images", "gallery")
ABOUT_DIR = os.path.join(ROOT, "images", "about")
MANIFEST = os.path.join(ROOT, "galleries", "manifest.js")
CAPTIONS = os.path.join(ROOT, "tools", "captions.json")

THUMB_EDGE = 700
LARGE_EDGE = 2560
Q_THUMB = 80
Q_LARGE = 86

# Leave these out of the grid (case-insensitive substring match).
EXCLUDE = ["screen shot", "screenshot"]
# Used for the About portrait (any substring match); not shown in the grid.
HEADSHOT_MATCH = ["headshot", "mike gibney"]
# Opening image of the gallery viewer (substring; falls back to first photo).
HERO_MATCH = "little tahoma"
# Full-screen splash photo the site loads on (substring match).
SPLASH_MATCH = "mack meadows"


def slugify(name):
    base = os.path.splitext(name)[0].lower()
    base = re.sub(r"[^a-z0-9]+", "-", base).strip("-")
    return base or "photo"


def load_captions():
    if os.path.exists(CAPTIONS):
        try:
            with open(CAPTIONS) as f:
                return json.load(f)
        except Exception as e:
            print("  ! couldn't read captions.json:", e)
    return {}


def save_resized(img, path, edge, q):
    im = ImageOps.exif_transpose(img).convert("RGB")
    w, h = im.size
    scale = min(1.0, edge / float(max(w, h)))
    if scale < 1.0:
        im = im.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
    im.save(path, "JPEG", quality=q, optimize=True, progressive=True)


def main():
    if not os.path.isdir(SRC_DIR):
        print("No photography/ folder found at", SRC_DIR)
        sys.exit(1)

    captions = load_captions()
    os.makedirs(OUT_DIR, exist_ok=True)

    files = sorted(
        f for f in os.listdir(SRC_DIR)
        if f.lower().endswith((".jpg", ".jpeg", ".png")) and not f.startswith(".")
    )

    photos = []
    hero_index = 0
    portrait = ""
    splash = ""

    for fname in files:
        low = fname.lower()
        if any(x in low for x in EXCLUDE):
            continue
        try:
            img = Image.open(os.path.join(SRC_DIR, fname))
        except Exception as e:
            print("  ! skipping", fname, e)
            continue

        if any(h in low for h in HEADSHOT_MATCH):
            os.makedirs(ABOUT_DIR, exist_ok=True)
            save_resized(img, os.path.join(ABOUT_DIR, "portrait.jpg"), 1200, 85)
            portrait = "images/about/portrait.jpg"
            print("  about portrait:", fname)
            continue

        slug = slugify(fname)
        thumb_rel = f"images/gallery/{slug}.thumb.jpg"
        large_rel = f"images/gallery/{slug}.large.jpg"
        save_resized(img, os.path.join(ROOT, thumb_rel), THUMB_EDGE, Q_THUMB)
        save_resized(img, os.path.join(ROOT, large_rel), LARGE_EDGE, Q_LARGE)

        if HERO_MATCH in low:
            hero_index = len(photos)
        if SPLASH_MATCH in low and not splash:
            splash = large_rel

        photos.append({
            "thumb": thumb_rel,
            "src": large_rel,
            "title": os.path.splitext(fname)[0],
            "caption": captions.get(fname, ""),
        })
        print("  +", fname)

    # Put the hero first
    if 0 <= hero_index < len(photos):
        photos.insert(0, photos.pop(hero_index))

    if not splash and photos:
        splash = photos[0]["src"]
    site = {"portrait": portrait, "splash": splash, "count": len(photos)}

    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    with open(MANIFEST, "w") as f:
        f.write("/* AUTO-GENERATED by tools/process-photos.py — do not edit by hand. */\n")
        f.write("window.PHOTOS = " + json.dumps(photos, indent=2) + ";\n")
        f.write("window.SITE = " + json.dumps(site, indent=2) + ";\n")

    print("\n✓ %d photos -> %s" % (len(photos), os.path.relpath(MANIFEST, ROOT)))


if __name__ == "__main__":
    main()
